"""Business logic: creating jobs and processing them."""
import logging
import re
from datetime import datetime, timezone
from pathlib import Path

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from . import config
from .certificate import render_certificate
from .database import SessionLocal
from .models import Certificate, CertificateStatus, Job, JobStatus
from .validation import RecipientData, validate_recipient

logger = logging.getLogger(__name__)


def create_job(db: Session, recipients: list) -> Job:
    """Store the job and one Certificate row per recipient.

    Invalid recipients are recorded immediately as FAILED (with the reason);
    valid ones start as PENDING and are generated by process_job().
    """
    job = Job(total=len(recipients), status=JobStatus.PENDING)
    db.add(job)
    db.flush()  # assigns job.id

    for idx, raw in enumerate(recipients):
        data, error = validate_recipient(raw)
        cert = Certificate(job_id=job.id, index=idx)
        raw_dict = raw if isinstance(raw, dict) else {}
        # keep whatever we can for identification, even if invalid
        cert.recipient_name = str(raw_dict.get("name"))[:255] if raw_dict.get("name") else None
        cert.recipient_email = str(raw_dict.get("email"))[:255] if raw_dict.get("email") else None
        cert.course_name = str(raw_dict.get("course_name"))[:255] if raw_dict.get("course_name") else None
        cert.issue_date = str(raw_dict.get("issue_date"))[:32] if raw_dict.get("issue_date") else None
        if error:
            cert.status = CertificateStatus.FAILED
            cert.error = f"Validation error - {error}"
        else:
            # store the cleaned values
            cert.recipient_name = data.name
            cert.recipient_email = data.email
            cert.course_name = data.course_name
            cert.issue_date = data.issue_date.isoformat()
        db.add(cert)

    db.commit()
    db.refresh(job)
    return job


def _safe_filename(index: int, name: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_")[:40] or "recipient"
    return f"{index + 1:05d}_{slug}.pdf"


def process_job(job_id: str, session_factory=SessionLocal) -> None:
    """Generate all pending certificates of a job (runs in the background).

    Every certificate is wrapped in its own try/except so a failure in one
    never stops the others.
    """
    db = session_factory()
    try:
        job = db.get(Job, job_id)
        if job is None:
            logger.error("process_job: job %s not found", job_id)
            return
        job.status = JobStatus.PROCESSING
        db.commit()

        pending = db.scalars(
            select(Certificate).where(
                Certificate.job_id == job_id,
                Certificate.status == CertificateStatus.PENDING,
            ).order_by(Certificate.index)
        ).all()

        job_dir = Path(config.CERTIFICATE_DIR) / job_id
        for cert in pending:
            try:
                data = RecipientData(
                    name=cert.recipient_name,
                    email=cert.recipient_email,
                    course_name=cert.course_name,
                    issue_date=cert.issue_date,
                )
                path = job_dir / _safe_filename(cert.index, data.name)
                render_certificate(data, path)
                cert.file_path = str(path)
                cert.status = CertificateStatus.SUCCESS
            except Exception as exc:  # noqa: BLE001 - isolate any per-item failure
                logger.exception("Certificate %s failed", cert.id)
                cert.status = CertificateStatus.FAILED
                cert.error = f"Generation error - {exc}"
            db.commit()  # commit per certificate -> live progress for status endpoint

        finalize_job(db, job)
    except Exception:  # noqa: BLE001
        logger.exception("Job %s crashed", job_id)
        db.rollback()
        job = db.get(Job, job_id)
        if job:
            job.status = JobStatus.FAILED
            job.completed_at = datetime.now(timezone.utc)
            db.commit()
    finally:
        db.close()


def finalize_job(db: Session, job: Job) -> None:
    counts = get_counts(db, job.id)
    if counts["succeeded"] == job.total:
        job.status = JobStatus.COMPLETED
    elif counts["succeeded"] == 0:
        job.status = JobStatus.FAILED
    else:
        job.status = JobStatus.PARTIALLY_COMPLETED
    job.completed_at = datetime.now(timezone.utc)
    db.commit()


def get_counts(db: Session, job_id: str) -> dict:
    rows = db.execute(
        select(Certificate.status, func.count())
        .where(Certificate.job_id == job_id)
        .group_by(Certificate.status)
    ).all()
    by_status = {status: n for status, n in rows}
    succeeded = by_status.get(CertificateStatus.SUCCESS, 0)
    failed = by_status.get(CertificateStatus.FAILED, 0)
    pending = by_status.get(CertificateStatus.PENDING, 0)
    return {
        "succeeded": succeeded,
        "failed": failed,
        "pending": pending,
        "processed": succeeded + failed,
    }
